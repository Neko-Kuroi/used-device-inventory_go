#!/usr/bin/env python3
"""Generate internal/db/migrations.go from the Python version's db.py.

The Python version is the specification: its SCHEMA, ADDED_COLUMNS and
SCHEMA_VERSION are extracted with the ast module (the file is parsed,
never imported) and emitted as Go data.  If the Python schema changes,
re-running this script produces a diff that is treated as a porting gap.

Usage: python3 tools/gen_migrations.py [path-to-db.py]
"""
import ast
import sqlite3
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_DB_PY = ROOT.parent / "used-device-inventory" / "device_app" / "db.py"
OUT = ROOT / "internal" / "db" / "migrations.go"


def extract(db_py: Path):
    tree = ast.parse(db_py.read_text(encoding="utf-8"))
    values = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1:
            name = getattr(node.targets[0], "id", None)
            if name in ("SCHEMA", "ADDED_COLUMNS", "SCHEMA_VERSION"):
                values[name] = ast.literal_eval(node.value)
    missing = {"SCHEMA", "ADDED_COLUMNS", "SCHEMA_VERSION"} - values.keys()
    if missing:
        raise SystemExit(f"{db_py}: could not extract {sorted(missing)}")
    return values["SCHEMA"], values["ADDED_COLUMNS"], values["SCHEMA_VERSION"]


def split_statements(schema: str):
    statements, buf = [], ""
    for line in schema.splitlines():
        buf += line + "\n"
        if sqlite3.complete_statement(buf):
            stmt = buf.strip()
            if stmt:
                statements.append(stmt)
            buf = ""
    if buf.strip():
        raise SystemExit("trailing incomplete SQL statement in SCHEMA")
    return statements


def go_string(s: str) -> str:
    if "`" not in s and "\\" not in s:
        return "`" + s + "`"
    escaped = s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return '"' + escaped + '"'


def main():
    db_py = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_DB_PY
    schema, added, version = extract(db_py)
    statements = split_statements(schema)

    lines = [
        "// Code generated by tools/gen_migrations.py from the Python",
        "// version's device_app/db.py. DO NOT EDIT.",
        "",
        "package db",
        "",
        f"// SchemaVersion is the value stored in PRAGMA user_version.",
        f"const SchemaVersion = {version}",
        "",
        "// SchemaStatements is the Python SCHEMA, split into single",
        "// statements, in order. Each ends with a semicolon.",
        "var SchemaStatements = []string{",
    ]
    for stmt in statements:
        lines.append(f"\t{go_string(stmt)},")
    lines += [
        "}",
        "",
        "// AddedColumns are the columns the Python migration adds to the",
        "// device table when they are missing, in the Python dict's order.",
        "var AddedColumns = []struct{ Name, Decl string }{",
    ]
    for name, decl in added.items():
        lines.append(f'\t{{"{name}", "{decl}"}},')
    lines.append("}")
    lines.append("")

    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}: {len(statements)} statements, "
          f"{len(added)} added columns, version {version}")


if __name__ == "__main__":
    main()
