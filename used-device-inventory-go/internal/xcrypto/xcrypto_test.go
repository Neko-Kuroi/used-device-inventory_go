package xcrypto

import (
	"crypto/sha1"
	"crypto/sha256"
	"crypto/sha512"
	"encoding/hex"
	"encoding/json"
	"hash"
	"os"
	"path/filepath"
	"testing"
)

type pbkdf2Vector struct {
	Digest     string `json:"digest"`
	Password   string `json:"password"`
	Salt       string `json:"salt"`
	Iterations int    `json:"iterations"`
	KeyLen     int    `json:"keylen"`
	Hex        string `json:"hex"`
}

type scryptVector struct {
	Password string `json:"password"`
	Salt     string `json:"salt"`
	N, R, P  int
	KeyLen   int    `json:"keylen"`
	Hex      string `json:"hex"`
}

func loadJSON(t *testing.T, name string, v any) {
	t.Helper()
	data, err := os.ReadFile(filepath.Join("testdata", name))
	if err != nil {
		t.Fatal(err)
	}
	if err := json.Unmarshal(data, v); err != nil {
		t.Fatal(err)
	}
}

// Vectors generated by Python's hashlib.pbkdf2_hmac.
func TestPBKDF2AgainstPython(t *testing.T) {
	var vectors []pbkdf2Vector
	loadJSON(t, "pbkdf2_vectors.json", &vectors)
	hashes := map[string]func() hash.Hash{
		"sha256": sha256.New, "sha512": sha512.New, "sha1": sha1.New,
	}
	for _, v := range vectors {
		got := PBKDF2([]byte(v.Password), []byte(v.Salt), v.Iterations,
			v.KeyLen, hashes[v.Digest])
		if hex.EncodeToString(got) != v.Hex {
			t.Errorf("pbkdf2 %s iter=%d pw=%q: got %x, want %s",
				v.Digest, v.Iterations, v.Password, got, v.Hex)
		}
	}
}

// Vectors generated by Python's hashlib.scrypt, including the
// Werkzeug parameter set (32768, 8, 1).
func TestScryptAgainstPython(t *testing.T) {
	var vectors []scryptVector
	loadJSON(t, "scrypt_vectors.json", &vectors)
	for _, v := range vectors {
		got, err := Scrypt([]byte(v.Password), []byte(v.Salt),
			v.N, v.R, v.P, v.KeyLen)
		if err != nil {
			t.Fatal(err)
		}
		if hex.EncodeToString(got) != v.Hex {
			t.Errorf("scrypt n=%d r=%d p=%d pw=%q:\n got %x\nwant %s",
				v.N, v.R, v.P, v.Password, got, v.Hex)
		}
	}
}

func TestScryptRejectsBadParams(t *testing.T) {
	if _, err := Scrypt([]byte("p"), []byte("s"), 1000, 8, 1, 32); err == nil {
		t.Error("N=1000 (not a power of two) accepted")
	}
	if _, err := Scrypt([]byte("p"), []byte("s"), 1, 8, 1, 32); err == nil {
		t.Error("N=1 accepted")
	}
}
